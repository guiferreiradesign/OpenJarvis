/**
 * The only door from hands-free mode into the chat. The chat input registers
 * one implementation that runs a turn through the normal conversation pipeline
 * (the same code a typed message uses); hands-free mode never builds its own
 * request. With nothing registered, a voice transcript is held for review.
 */
export type VoiceTurnStatus = 'completed' | 'failed' | 'aborted' | 'rejected';

export interface VoiceTurnResult {
  status: VoiceTurnStatus;
  /** Id of the assistant message that holds the reply (completed turns only). */
  messageId?: string;
  /** The finished reply text (completed turns only). */
  text?: string;
}

export interface ChatBridge {
  /** Current text in the chat input, including anything the user is typing. */
  getDraft(): string;
  /** False while a reply is streaming or no model is selected. */
  canSubmit(): boolean;
  /** Run one voice-originated turn through the existing chat pipeline. */
  submit(text: string): Promise<VoiceTurnResult>;
  /** Stop the reply currently being generated by a voice turn. */
  abort(): void;
  /** Global voice-output setting: when false nothing is ever spoken. */
  speechOutputEnabled(): boolean;
}

let current: ChatBridge | null = null;
const draftListeners = new Set<(draft: string) => void>();

export function registerChatBridge(bridge: ChatBridge): () => void {
  current = bridge;
  return () => {
    if (current === bridge) current = null;
  };
}

export function getChatBridge(): ChatBridge | null {
  return current;
}

/** The chat input calls this whenever its text changes. */
export function notifyDraftChanged(draft: string): void {
  draftListeners.forEach((fn) => fn(draft));
}

export function onDraftChanged(fn: (draft: string) => void): () => void {
  draftListeners.add(fn);
  return () => draftListeners.delete(fn);
}

// Assistant messages created by voice turns. Hands-free mode speaks these
// itself, so the typed-message autoplay must leave them alone (no double
// synthesis). Bounded so a long session cannot grow it without limit.
const voiceReplyIds: string[] = [];
const MAX_TRACKED = 64;

export function markVoiceReply(messageId: string): void {
  if (voiceReplyIds.includes(messageId)) return;
  voiceReplyIds.push(messageId);
  if (voiceReplyIds.length > MAX_TRACKED) voiceReplyIds.shift();
}

export function isVoiceReply(messageId: string | undefined | null): boolean {
  return !!messageId && voiceReplyIds.includes(messageId);
}

export function __resetBridgeForTests(): void {
  current = null;
  draftListeners.clear();
  voiceReplyIds.length = 0;
}
